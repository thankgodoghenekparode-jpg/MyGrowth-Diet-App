/**
 * Flatten the plan into one entry per calendar day of 2027.
 * @returns {{date: string, month: number, day: number, reading: string, heading: string, focus: string, note: string|null}[]}
 */
export function scriptureReadingDays2027() {
  const days = [];
  for (const month of SCRIPTURE_READING_2027) {
    month.readings.forEach((reading, index) => {
      const day = index + 1;
      days.push({
        date: `2027-${String(month.month).padStart(2, '0')}-${String(day).padStart(2, '0')}`,
        month: month.month,
        day,
        reading,
        heading: month.heading,
        focus: month.focus,
        note: month.note ?? null,
      });
    });
  }
  return days;
}

